#!/usr/bin/env node
'use strict';

// Builds REFERENCE.md: the copy-ready markup for every token, shell, page
// header and component, from the same sources the preview uses
// (kit.css, preview/catalog.js, preview/page-*.html). Run after any change:
//   node scripts/check.js && node scripts/build-reference.js

const fs = require('fs');
const path = require('path');
const vm = require('vm');

const root = path.join(__dirname, '..');
const read = (p) => fs.readFileSync(path.join(root, p), 'utf8');

const kit = read('kit.css');
const sandbox = { window: {} };
vm.runInNewContext(read('preview/catalog.js'), sandbox);
const catalog = sandbox.window.KIT_CATALOG;

// Tokens: the light :root block, with their comments.
const tokenBlock = kit.slice(kit.indexOf(':root {'), kit.indexOf('}', kit.indexOf(':root {')) + 1);

// Shells, cut from the page templates so they match the previews exactly.
const cut = (file, start, end) => {
  const src = read(file);
  const a = src.indexOf(start);
  const b = src.indexOf(end, a) + end.length;
  return src.slice(a, b);
};
const appFrame = cut('preview/page-list.html', '<div class="app">', '<div class="mobile-bar">');
const pageHead = cut('preview/page-record.html', '<header class="page-header">', '</header>');

const fence = (lang, code) => `\`\`\`${lang}\n${code.trim()}\n\`\`\``;

let md = `# Astrodock app design system: reference

Generated by \`scripts/build-reference.js\` from \`kit.css\` and \`preview/catalog.js\`. Do not edit by hand.
The rules live in README.md; this file is the markup. The live versions are in \`preview/\` (open \`preview/index.html\`).

## Using it

- Load \`kit.css\` first, then the app's \`theme.css\` (tokens only). Load Geist: \`<link href="https://fonts.googleapis.com/css2?family=Geist:wght@400;500;600&family=Geist+Mono:wght@400;500&display=swap" rel="stylesheet">\`.
- Set \`data-theme\` on \`<html>\`: \`light\`, \`dark\` or \`auto\`.
- Icons: \`<svg class="icon"><use href="#i-NAME"/></svg>\` below stands for the Lucide icon NAME. In React: \`<Plus className="icon" />\`; small: \`className="icon icon-sm"\`.
- Behavior hooks are data attributes (\`data-toggle\`, \`data-open\`, \`data-row-check\`...). In the preview, \`preview/preview.js\` wires them; in an app, the React components do.
- Run \`node scripts/check.js\` after changing kit.css or adding markup to the previews or catalog.

## Rules that are easy to get wrong

- One look per thing: every checkbox and radio is the global style (never \`accent-color\`, never a custom box); every menu row, option and nav row is \`.item\`; every button, input and select trigger shares the control size.
- Radius: \`--radius-xs\` marks (checkbox, citation, kbd), \`--radius-sm\` controls and items, \`--radius-md\` surfaces (cards, popovers, modals, toasts). Avatars and tiles are rounded squares (\`.avatar\`), never circles.
- No raw colors, sizes, radii, weights or shadows in app CSS. No inline styles except a custom property for a data value (\`style="--value: 32%"\`).
- A list or table inside a card is flat (\`.flush\`, or \`.card-body.flush-x\` for rows).
- Active state: an underline for horizontal navigation (\`.tab\`, shell sections), the selected fill for vertical (\`.item\` with \`aria-current\`).
- Toasts confirm and offer Undo; errors people must act on go in the page.

## Tokens

${fence('css', tokenBlock)}

## App frame: sidebar and panel

The sidebar sits on the gray frame; the page sits on one white panel. Every app uses this frame.

${fence('html', appFrame + '\n    <main class="page">…</main>\n  </div>\n</div>')}

## Page header (back, title, actions, tabs)

${fence('html', pageHead)}

`;

for (const g of catalog) {
  md += `## ${g.group}\n\n`;
  for (const c of g.components) {
    md += `### ${c.title}\n\n${c.lede}\n\n`;
    if (c.use) md += `- **Use for:** ${c.use}\n`;
    if (c.notFor) md += `- **Not for:** ${c.notFor}\n`;
    if (c.use || c.notFor) md += '\n';
    for (const ex of c.examples) {
      md += `**${ex.title}.**${ex.desc ? ` ${ex.desc}` : ''}\n\n${fence('html', ex.html)}\n\n`;
    }
  }
}

md += `## Page types

Every screen is one of these; open the preview file for the full markup.

| Page type | Preview | Anatomy |
|---|---|---|
| Collection | \`preview/page-list.html\` | Back, header with actions, tabs, summary links, filter sidebar, toolbar, grouped list or cards, bulk bar |
| Record | \`preview/page-record.html\` | Back, header with avatar and labels, tabs, nav list of sections, summary cards first, sections with Show detail |
| Create and edit | \`preview/page-form.html\` | Narrow page, error summary notice, fieldsets, save bar |
| Settings | \`preview/page-settings.html\` | Section root, nav list of groups, one card per group with its own Save, danger zone last |
| Dashboard | \`preview/page-dashboard.html\` | Stat links, chart card, project cards, needs attention, running now |
| Background work | \`preview/page-activity.html\` | Tabs Now, History, Usage and cost; lanes with running work; failures with Retry; drawer detail |
| Step by step | \`preview/page-wizard.html\` | Steps, one card per step, Back and Next in the card foot |
| Sidebar shell and queue | \`preview/page-sidebar.html\` | Sidebar shell; queue on the left, detail with its own bar on the right; command menu |
| System | \`preview/page-states.html\` | Signing in, no access, not found, error, first use, loading, saving failed |
`;

fs.writeFileSync(path.join(root, 'REFERENCE.md'), md);
console.log(`REFERENCE.md: ${catalog.reduce((n, g) => n + g.components.length, 0)} components, ${md.split('\n').length} lines`);
